/** Escape for safe HTML output. */
function e(?string $value): string
{
    return htmlspecialchars($value ?? '', ENT_QUOTES, 'UTF-8');
}

function redirect(string $path): never
{
    header("Location: {$path}");
    exit;
}

/** Builds a displayable URL for a stored salon logo_path — either a full R2 URL, or (for rows saved before uploads moved to R2) a legacy local path. */
function salon_logo_url(?string $storedPath): ?string
{
    if ($storedPath === null || $storedPath === '') {
        return null;
    }

    return str_starts_with($storedPath, 'http://') || str_starts_with($storedPath, 'https://')
        ? $storedPath
        : '/uploads/' . $storedPath;
}

function flash_set(string $type, string $message): void
{
    $_SESSION['flash'] = ['type' => $type, 'message' => $message];
}

function flash_get(): ?array
{
    $flash = $_SESSION['flash'] ?? null;
    unset($_SESSION['flash']);

    return $flash;
}

/** Stash submitted form values so a failed form can be redisplayed pre-filled after a redirect. */
function old_input_set(array $data): void
{
    $_SESSION['old_input'] = $data;
}

/** @return array<string, mixed> */
function old_input_get(): array
{
    $old = $_SESSION['old_input'] ?? [];
    unset($_SESSION['old_input']);

    return $old;
}

/** Stash per-field validation messages so a failed form can show them after a redirect. */
function form_errors_set(array $errors): void
{
    $_SESSION['form_errors'] = $errors;
}

/** @return array<string, string> */
function form_errors_get(): array
{
    $errors = $_SESSION['form_errors'] ?? [];
    unset($_SESSION['form_errors']);

    return $errors;
}

function current_admin(): ?array
{
    return $_SESSION['admin'] ?? null;
}

/** Human-readable relative time, e.g. "5m ago", "2h ago", "3d ago". */
function time_ago(string $datetime): string
{
    $diffSeconds = max(0, time() - strtotime($datetime));

    if ($diffSeconds < 60) {
        return 'just now';
    }
    if ($diffSeconds < 3600) {
        return intdiv($diffSeconds, 60) . 'm ago';
    }
    if ($diffSeconds < 86400) {
        return intdiv($diffSeconds, 3600) . 'h ago';
    }

    return intdiv($diffSeconds, 86400) . 'd ago';
}

